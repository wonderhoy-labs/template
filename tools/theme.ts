// Shared by every Wonderhoy Labs repository. Change it in wonderhoy-labs/template first.
//
// Makes the Material 3 colour scheme from the character's image colour in package.json, and writes it where
// each part of the project reads it: web/src/ui/theme.css and web/src/brand.ts for the web app, and ui/Theme.kt
// and res/values*/theme_colors.xml for the Android app. Run `pnpm theme` after changing the brand, and
// `pnpm theme --check` to see whether the files are current.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { argbFromHex, Hct, SchemeContent } from "@material/material-color-utilities";

export interface Brand {
	/** The product name, as people read it: "Saki". */
	name: string;
	/** Lowercase identifier: the repository, package and command name. */
	id: string;
	/** One sentence that says what it does. */
	tagline: string;
	/** The Project SEKAI character the project is named for. */
	character: string;
	/** That character's unit. */
	unit: string;
	/** The character's image colour, as #RRGGBB. */
	color: string;
}

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function readBrand(dir = root): Brand {
	const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
		name: string;
		wonderhoy?: Omit<Brand, "id">;
	};
	if (!pkg.wonderhoy) throw new Error('package.json has no "wonderhoy" block');
	const brand = { ...pkg.wonderhoy, id: pkg.name };
	for (const key of ["name", "tagline", "character", "unit", "color"] as const) {
		if (typeof brand[key] !== "string" || brand[key] === "") throw new Error(`wonderhoy.${key} is missing`);
	}
	if (!/^#[0-9A-F]{6}$/.test(brand.color)) throw new Error("wonderhoy.color must look like #RRGGBB, in capitals");
	if (!/^[a-z][a-z0-9-]*$/.test(brand.id)) throw new Error("package.json name must be the lowercase project id");
	return brand;
}

/** Material colour roles, in the order the files list them. */
const ROLES = [
	"primary",
	"onPrimary",
	"primaryContainer",
	"onPrimaryContainer",
	"inversePrimary",
	"secondary",
	"onSecondary",
	"secondaryContainer",
	"onSecondaryContainer",
	"tertiary",
	"onTertiary",
	"tertiaryContainer",
	"onTertiaryContainer",
	"error",
	"onError",
	"errorContainer",
	"onErrorContainer",
	"background",
	"onBackground",
	"surface",
	"onSurface",
	"surfaceVariant",
	"onSurfaceVariant",
	"surfaceDim",
	"surfaceBright",
	"surfaceContainerLowest",
	"surfaceContainerLow",
	"surfaceContainer",
	"surfaceContainerHigh",
	"surfaceContainerHighest",
	"inverseSurface",
	"inverseOnSurface",
	"outline",
	"outlineVariant",
	"scrim",
	"surfaceTint",
] as const;

type Role = (typeof ROLES)[number];

export type Colors = Record<Role, number>;

/**
 * In the light theme, Material's content scheme keeps the image colour itself as the primary container. In the dark
 * theme that same pale container would glare, and a primary button on it all but disappears (Saki's yellow did both),
 * so dark primary and tertiary roles use Material's usual tones instead: 80, 20, 30 and 90, still in the character's
 * hue and chroma.
 */
export function schemes(color: string): { light: Colors; dark: Colors } {
	const source = Hct.fromInt(argbFromHex(color));
	const resolve = (dark: boolean): Colors => {
		const scheme = new SchemeContent(source, dark, 0);
		const colors = Object.fromEntries(ROLES.map((role) => [role, scheme[role]])) as Colors;
		if (dark) {
			const { primaryPalette: p, tertiaryPalette: t } = scheme;
			Object.assign(colors, {
				primary: p.tone(80),
				onPrimary: p.tone(20),
				primaryContainer: p.tone(30),
				onPrimaryContainer: p.tone(90),
				inversePrimary: p.tone(40),
				surfaceTint: p.tone(80),
				tertiary: t.tone(80),
				onTertiary: t.tone(20),
				tertiaryContainer: t.tone(30),
				onTertiaryContainer: t.tone(90),
			});
		}
		return colors;
	};
	return { light: resolve(false), dark: resolve(true) };
}

const rgb = (argb: number) => [(argb >> 16) & 255, (argb >> 8) & 255, argb & 255];
const hex = (argb: number) => (argb & 0xffffff).toString(16).toUpperCase().padStart(6, "0");
const kebab = (role: string) => role.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
/** mdui calls surfaceTint by its older name. */
const mduiName = (role: Role) => (role === "surfaceTint" ? "surface-tint-color" : kebab(role));

function header(brand: Brand, prefix: string): string {
	return `${prefix}Generated by tools/theme.ts from ${brand.color}, the image colour of ${brand.character} (${brand.unit}).
${prefix}Change the "wonderhoy" block in package.json and run \`pnpm theme\` instead of editing this file.`;
}

export function css(brand: Brand): string {
	const { light, dark } = schemes(brand.color);
	const lines: string[] = [];
	for (const [scheme, mode] of [
		[light, "light"],
		[dark, "dark"],
	] as const) {
		for (const role of ROLES) {
			lines.push(`\t--mdui-color-${mduiName(role)}-${mode}: ${rgb(scheme[role]).join(", ")};`);
		}
	}
	return `/*
${header(brand, " * ")}
 */
:root:root {
\t--wonderhoy-brand: ${rgb(argbFromHex(brand.color)).join(", ")};
${lines.join("\n")}
}
`;
}

/** One property of brand.ts, wrapped the way Biome wraps it when it doesn't fit in 120 columns with tabs 4 wide. */
function tsField(key: string, value: string): string {
	const text = JSON.stringify(value);
	return 4 + key.length + 2 + text.length + 1 > 120 ? `\t${key}:\n\t\t${text},` : `\t${key}: ${text},`;
}

export function ts(brand: Brand): string {
	const fields: [string, string][] = [
		["name", brand.name],
		["id", brand.id],
		["tagline", brand.tagline],
		["character", brand.character],
		["unit", brand.unit],
		["color", brand.color],
		["repository", `https://github.com/wonderhoy-labs/${brand.id}`],
	];
	return `${header(brand, "// ")}

export const brand = {
${fields.map(([key, value]) => tsField(key, value)).join("\n")}
} as const;
`;
}

export function kotlin(brand: Brand): string {
	const { light, dark } = schemes(brand.color);
	const pkg = `com.wonderhoylabs.${brand.id.replace(/-/g, "")}.ui`;
	const colors = (scheme: Colors) => ROLES.map((role) => `\t${role} = Color(0xFF${hex(scheme[role])}),`).join("\n");
	const kstring = (s: string) => JSON.stringify(s).replace(/\$/g, "\\$");
	return `${header(brand, "// ")}
package ${pkg}

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color

/** What the app is called, and who it's named for. */
object Brand {
\tconst val NAME = ${kstring(brand.name)}
\tconst val TAGLINE = ${kstring(brand.tagline)}
\tconst val CHARACTER = ${kstring(brand.character)}
\tconst val UNIT = ${kstring(brand.unit)}
\tconst val REPOSITORY = ${kstring(`https://github.com/wonderhoy-labs/${brand.id}`)}
\tval color = Color(0xFF${brand.color.slice(1)})
}

private val LightColors = lightColorScheme(
${colors(light)}
)

private val DarkColors = darkColorScheme(
${colors(dark)}
)

@Composable
fun ${brand.name.replace(/[^A-Za-z0-9]/g, "")}Theme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
\tMaterialTheme(colorScheme = if (darkTheme) DarkColors else LightColors, content = content)
}
`;
}

/** The colours Android needs before Compose draws anything: the window behind the app, and the brand. */
export function xml(brand: Brand, dark: boolean): string {
	const scheme = schemes(brand.color)[dark ? "dark" : "light"];
	return `<?xml version="1.0" encoding="utf-8"?>
<!--
${header(brand, "\t")}
-->
<resources>
\t<color name="window_background">#${hex(scheme.background)}</color>
\t<color name="brand">${brand.color}</color>
</resources>
`;
}

/** Every file this writes, relative to the repository, with what it should contain. */
export function outputs(brand: Brand, dir = root): Map<string, string> {
	const files = new Map<string, string>();
	if (existsSync(join(dir, "web/package.json"))) {
		files.set("web/src/ui/theme.css", css(brand));
		files.set("web/src/brand.ts", ts(brand));
	}
	if (existsSync(join(dir, "android/app"))) {
		const pkgDir = `com/wonderhoylabs/${brand.id.replace(/-/g, "")}`;
		files.set(`android/app/src/main/kotlin/${pkgDir}/ui/Theme.kt`, kotlin(brand));
		files.set("android/app/src/main/res/values/theme_colors.xml", xml(brand, false));
		files.set("android/app/src/main/res/values-night/theme_colors.xml", xml(brand, true));
	}
	return files;
}

if (import.meta.main) {
	const check = process.argv.includes("--check");
	const brand = readBrand();
	let stale = 0;
	for (const [path, text] of outputs(brand)) {
		const file = join(root, path);
		const current = existsSync(file) ? readFileSync(file, "utf8") : "";
		if (current === text) continue;
		if (check) {
			console.error(`${path} doesn't match ${brand.color}. Run \`pnpm theme\`.`);
			stale++;
		} else {
			mkdirSync(dirname(file), { recursive: true });
			writeFileSync(file, text);
			console.info(`Wrote ${path}`);
		}
	}
	if (stale > 0) process.exit(1);
}
